// Captcha payloads carried on the game IPC (verified against the in-game component and the
// standalone solver's wire contract):
//   CaptchaRequest  = { requestId, imageBase64, mimeType }        (game -> host)
//   CaptchaOutcome  = { requestId, success, message }             (game -> host)
//   answer          = Command { command: "SubmitCaptchaAnswer",
//                               args: { requestId, answer, error, forceLogout } }  (host -> game)
public sealed record CaptchaGameRequest(string RequestId, string ImageBase64, string? MimeType);

public sealed record CaptchaGameOutcome(string RequestId, bool? Success, string? Message);

// Solver key material, generated by the same script that produced the standalone solver's key.
// Regenerate via scripts to rotate. The decryption material travels with the executable, so this
// is obfuscation, not protection against a determined user.
internal static class CaptchaSolverKey
{
    private const bool Enabled = true;
    private static readonly byte[] PartA = [0x73, 0xB9, 0x90, 0x1C, 0x8B, 0x81, 0x73, 0x97, 0xA1, 0xD4, 0x83, 0xF4, 0x4F, 0x9F, 0x60, 0x9F];
    private static readonly byte[] PartB = [0x25, 0x15, 0x6B, 0x11, 0x83, 0x36, 0x1F, 0x52, 0xD2, 0xFF, 0x69, 0xBB, 0xAB, 0xF3, 0x34, 0x8E];
    private static readonly byte[] Cipher = [0x2D, 0xCA, 0xEE, 0xB8, 0x2C, 0xF8, 0x4E, 0x8D, 0xDC, 0x01, 0x11, 0x19, 0x3B, 0xE1, 0x65, 0xC9, 0x79, 0x33, 0xC8, 0xED, 0xE8, 0x05, 0x1E, 0xC5, 0x9A, 0x02, 0xDD, 0xCC, 0x16, 0x97, 0x8C, 0x23, 0xAC, 0x5C, 0xE3, 0x81, 0x46, 0x87, 0xB3, 0x68, 0x5A, 0x00, 0xCB, 0xE3, 0x34, 0xB9, 0x33, 0xCE];
    private static readonly byte[] Iv = [0x17, 0x1B, 0x0F, 0x81, 0xC9, 0xAA, 0x1B, 0xE8, 0xD7, 0x68, 0xAF, 0x7C, 0xA6, 0xC5, 0x95, 0x72];

    public static string? Unlock()
    {
        if (!Enabled || Cipher.Length == 0 || Iv.Length != 16 || PartA.Length + PartB.Length != 32)
            return null;
        try
        {
            using var aes = Aes.Create();
            aes.Mode = CipherMode.CBC;
            aes.Padding = PaddingMode.PKCS7;
            aes.Key = [.. PartA, .. PartB];
            aes.IV = Iv;
            using var decryptor = aes.CreateDecryptor();
            var plain = decryptor.TransformFinalBlock(Cipher, 0, Cipher.Length);
            var key = Encoding.UTF8.GetString(plain).Trim();
            return key.Length > 0 ? key : null;
        }
        catch (CryptographicException)
        {
            return null;
        }
    }
}

// The updater's shared recognition service: the customer's updater login authorizes challenges
// on the regional endpoints. The authorization token lives in a disguised registry location —
// verified against the updater's own client, including the JSON envelope and task lifecycle.
public sealed class CaptchaServicePermanentException(string message) : InvalidOperationException(message);

public sealed class AionRecognitionClient(Func<string?>? tokenResolver = null, string[]? endpoints = null, HttpClient? httpClient = null) : IDisposable
{
    private static readonly string[] DefaultEndpoints =
    [
        "https://decode-ty.aion.onl",
        "https://decode-sg.aion.onl",
        "https://decode-hk.aion.onl",
    ];
    private const string CreatePath = "/api/v8/55bff2a9-2611-4d73-94e9-3f4f8ebfe9e4";
    private const string PollPath = "/api/v8/5bf5a8c6-f122-4b67-8230-30d4d6ec73c6";
    private readonly HttpClient http = httpClient ?? new HttpClient(new HttpClientHandler { AllowAutoRedirect = false }) { Timeout = TimeSpan.FromSeconds(20) };
    private readonly string[] resolvedEndpoints = endpoints is { Length: > 0 } ? endpoints : DefaultEndpoints;
    private readonly Func<string?> resolvedTokenResolver = tokenResolver ?? ReadVendorAuthorizationToken;
    private readonly bool ownsHttpClient = httpClient is null;

    public static string? ReadVendorAuthorizationToken()
    {
        try
        {
            using var pointer = Registry.CurrentUser.OpenSubKey(@"Software\Microsoft\Windows\CurrentVersion\Reliability");
            var machineId = pointer?.GetValue("MachineId") as string;
            if (string.IsNullOrWhiteSpace(machineId)) return null;
            using var state = Registry.CurrentUser.OpenSubKey("Software\\Microsoft\\" + machineId);
            var raw = state?.GetValue("V6AuthorizationState") as string;
            if (raw is null) return null;
            using var document = JsonDocument.Parse(raw);
            var root = document.RootElement;
            if (!root.TryGetProperty("schemaVersion", out var version) || version.GetInt32() != 1) return null;
            if (!root.TryGetProperty("token", out var token)) return null;
            var value = token.GetString();
            if (string.IsNullOrWhiteSpace(value)) return null;
            // The login is refreshed by the updater; skip the service entirely once it expires.
            if (root.TryGetProperty("expiryTime", out var expiry) && expiry.TryGetInt64(out var expiryMs) && expiryMs > 0
                && DateTimeOffset.UtcNow.ToUnixTimeMilliseconds() >= expiryMs) return null;
            return value.Trim();
        }
        catch (Exception e) when (e is IOException or UnauthorizedAccessException or System.Security.SecurityException
            or System.Text.Json.JsonException or InvalidOperationException or ArgumentException)
        {
            return null;
        }
    }

    public void Dispose()
    {
        if (ownsHttpClient) http.Dispose();
    }

    public async Task<string> SolveAsync(string imageBase64, CancellationToken stop)
    {
        var token = resolvedTokenResolver()?.Trim();
        if (string.IsNullOrWhiteSpace(token))
            throw new InvalidOperationException("The recognition service is not signed in.");
        var image = Convert.FromBase64String(imageBase64.Trim());
        if (image.Length is 0 or > 6_291_456)
            throw new InvalidDataException("Captcha image is empty or too large.");
        var payload = imageBase64.Trim();
        using var deadline = CancellationTokenSource.CreateLinkedTokenSource(stop);
        deadline.CancelAfter(TimeSpan.FromSeconds(45));
        string? permanent = null;
        for (var attempt = 0; attempt < resolvedEndpoints.Length * 2 && !deadline.IsCancellationRequested; attempt++)
        {
            try
            {
                return await RecognizeOnce(resolvedEndpoints[attempt % resolvedEndpoints.Length], token, payload, deadline.Token);
            }
            catch (CaptchaServicePermanentException e)
            {
                permanent = e.Message;
                break;
            }
            catch (OperationCanceledException) when (stop.IsCancellationRequested)
            {
                throw;
            }
            catch (OperationCanceledException)
            {
                break;
            }
            catch (Exception)
            {
                await Task.Delay(TimeSpan.FromSeconds(1), deadline.Token);
            }
        }
        throw permanent is { Length: > 0 }
            ? new CaptchaServicePermanentException(permanent)
            : new InvalidOperationException("The recognition service did not answer in time.");
    }

    private async Task<string> RecognizeOnce(string endpoint, string token, string payload, CancellationToken stop)
    {
        var create = await PostAsync(endpoint + CreatePath, new Dictionary<string, object?>
        {
            ["authorizationToken"] = token,
            ["task"] = new Dictionary<string, object?> { ["type"] = "Aion2", ["body"] = payload },
        }, stop);
        var immediate = SolutionText(create);
        if (!string.IsNullOrWhiteSpace(immediate)) return immediate.Trim();
        var taskId = create.TryGetProperty("taskId", out var id) ? id.ToString() : "";
        if (string.IsNullOrWhiteSpace(taskId))
            throw new InvalidDataException("The recognition service returned no task ID.");
        while (true)
        {
            await Task.Delay(TimeSpan.FromSeconds(1), stop);
            var poll = await PostAsync(endpoint + PollPath, new Dictionary<string, object?>
            {
                ["authorizationToken"] = token,
                ["taskId"] = taskId,
            }, stop);
            var status = poll.TryGetProperty("status", out var state) ? state.GetString() : null;
            if (status == "ready")
                return SolutionText(poll)?.Trim() is { Length: > 0 } text
                    ? text : throw new InvalidDataException("The recognition service returned no answer text.");
            if (status != "processing")
                throw new InvalidOperationException("The recognition service returned an unknown task status.");
        }
    }

    private async Task<JsonElement> PostAsync(string url, Dictionary<string, object?> body, CancellationToken stop)
    {
        using var response = await http.PostAsJsonAsync(url, body, JsonOptions, stop);
        var statusCode = (int)response.StatusCode;
        if (statusCode is 404 or 410 or 426)
            throw new CaptchaServicePermanentException($"The recognition service declined this interface (HTTP {statusCode}); the updater needs an upgrade.");
        response.EnsureSuccessStatusCode();
        using var document = await JsonDocument.ParseAsync(
            await response.Content.ReadAsStreamAsync(stop), cancellationToken: stop);
        var root = document.RootElement.Clone();
        var errorId = root.TryGetProperty("errorId", out var eid) ? eid.GetInt32() : 0;
        var success = root.TryGetProperty("success", out var ok) ? ok.GetBoolean() : true;
        if (errorId == 0 && success) return root;
        var code = root.TryGetProperty("errorCode", out var ec) ? ec.GetString()
            : root.TryGetProperty("code", out var c) ? c.GetString() : null;
        var description = root.TryGetProperty("errorDescription", out var ed) ? ed.GetString()
            : root.TryGetProperty("error", out var e2) ? e2.GetString() : null;
        if (string.Equals(code, "CLIENT_UPGRADE_REQUIRED", StringComparison.OrdinalIgnoreCase))
            throw new CaptchaServicePermanentException(description ?? "The recognition service requires a newer updater.");
        throw new InvalidOperationException($"The recognition service rejected the task ({code ?? "UNKNOWN_ERROR"}: {description ?? "unknown error"}).");
    }

    private static string? SolutionText(JsonElement root) =>
        root.TryGetProperty("solution", out var solution) &&
        solution.TryGetProperty("text", out var text) ? text.GetString() : null;

    private static readonly JsonSerializerOptions JsonOptions = new(JsonSerializerDefaults.Web);
}

public sealed class YesCaptchaClient(HttpClient http, string endpoint, string clientKey)
{
    private static readonly JsonSerializerOptions JsonOptions = new(JsonSerializerDefaults.Web);

    public async Task<string> SolveAsync(string imageBase64, CancellationToken stop)
    {
        var image = Convert.FromBase64String(imageBase64.Trim());
        if (image.Length is 0 or > 6_291_456)
            throw new InvalidDataException("Captcha image is empty or too large.");
        using var deadline = CancellationTokenSource.CreateLinkedTokenSource(stop);
        deadline.CancelAfter(TimeSpan.FromSeconds(90));
        var create = await PostAsync("/createTask", new
        {
            clientKey,
            task = new { type = "ImageToTextTask", body = imageBase64.Trim() }
        }, deadline.Token);
        string? answer = SolutionText(create);
        if (!string.IsNullOrWhiteSpace(answer)) return answer.Trim();
        string taskId = create.GetProperty("taskId").ToString();
        if (string.IsNullOrWhiteSpace(taskId) || taskId == "0")
            throw new InvalidDataException("The captcha service returned no task ID.");
        while (true)
        {
            await Task.Delay(3000, deadline.Token);
            var result = await PostAsync("/getTaskResult", new { clientKey, taskId }, deadline.Token);
            if (result.TryGetProperty("status", out var status) && status.GetString() == "ready")
                return SolutionText(result)?.Trim() is { Length: > 0 } text
                    ? text : throw new InvalidDataException("The captcha service returned no answer text.");
            if (!result.TryGetProperty("status", out status) || status.GetString() != "processing")
                throw new InvalidDataException("Unexpected captcha service task status.");
        }
    }

    private async Task<JsonElement> PostAsync(string path, object body, CancellationToken stop)
    {
        using var response = await http.PostAsJsonAsync(endpoint + path, body, JsonOptions, stop);
        response.EnsureSuccessStatusCode();
        using var document = await JsonDocument.ParseAsync(
            await response.Content.ReadAsStreamAsync(stop), cancellationToken: stop);
        var root = document.RootElement;
        if (root.TryGetProperty("errorId", out var id) && id.GetInt32() != 0)
        {
            string message = root.TryGetProperty("errorDescription", out var detail)
                ? detail.GetString() ?? "Unknown error" : "Unknown error";
            throw new InvalidOperationException($"Captcha service: {message}");
        }
        return root.Clone();
    }

    private static string? SolutionText(JsonElement root) =>
        root.TryGetProperty("solution", out var solution) &&
        solution.TryGetProperty("text", out var text) ? text.GetString() : null;
}

// Auto-resolve: when the game signals a challenge on the direct IPC, solve it with the captcha
// service and submit the answer back on the same connection. Only challenges the game itself
// requests are processed; Hexor never proactively opens or reads challenge screens.
public sealed class CaptchaAutoSolver : IDisposable
{
    private readonly GameIpcManager manager;
    private readonly Func<string, CancellationToken, Task<string>> solve;
    private readonly AionRecognitionClient? vendorClient;
    private readonly ConcurrentDictionary<string, byte> pending = new();
    private readonly ConcurrentDictionary<string, byte> seenRequests = new();
    private int solved;
    private int rejected;
    private int failed;
    private string lastEvent = "Auto-resolve is armed. It answers a challenge as soon as the game shows one.";
    private DateTimeOffset? lastEventAt;
    private readonly bool enabled;
    private readonly int minimumAnswerDelayMs;
    private readonly int maximumAnswerDelayMs;
    private readonly object historyLock = new();
    private readonly List<(DateTimeOffset At, string Text)> history = new();
    private string lastProvider = "";

    public CaptchaAutoSolver(GameIpcManager manager, Func<string, CancellationToken, Task<string>>? solveOverride = null, string? keyOverride = null,
        int minimumAnswerDelayMs = 700, int maximumAnswerDelayMs = 2200, Func<string?>? vendorTokenResolver = null,
        Func<string, CancellationToken, Task<string>>? vendorSolveOverride = null)
    {
        this.manager = manager;
        this.minimumAnswerDelayMs = Math.Clamp(minimumAnswerDelayMs, 0, 10_000);
        this.maximumAnswerDelayMs = Math.Clamp(Math.Max(maximumAnswerDelayMs, this.minimumAnswerDelayMs), this.minimumAnswerDelayMs, 15_000);
        var key = keyOverride ?? CaptchaSolverKey.Unlock();
        // Primary: the updater's shared recognition service (no key, uses the updater login).
        // Failover: the embedded recognition key. A direct solve override replaces the whole chain.
        vendorClient = solveOverride is null
            ? vendorSolveOverride is { } injected ? null : new AionRecognitionClient(vendorTokenResolver)
            : null;
        Func<string, CancellationToken, Task<string>>? vendorSolve = solveOverride is { }
            ? null
            : vendorSolveOverride ?? (vendorClient is null ? null : new Func<string, CancellationToken, Task<string>>(vendorClient.SolveAsync));
        var vendorToken = vendorSolveOverride is { }
            ? "injected"
            : (vendorTokenResolver ?? AionRecognitionClient.ReadVendorAuthorizationToken)();
        enabled = !string.IsNullOrWhiteSpace(key) || vendorSolve is { } && !string.IsNullOrWhiteSpace(vendorToken);
        if (enabled)
        {
            Func<string, CancellationToken, Task<string>> backup;
            if (!string.IsNullOrWhiteSpace(key))
            {
                var http = new HttpClient { Timeout = TimeSpan.FromSeconds(30) };
                var endpoint = Environment.GetEnvironmentVariable("YESCAPTCHA_BASE_URL")?.TrimEnd('/') ?? "https://api.yescaptcha.com";
                backup = new YesCaptchaClient(http, endpoint, key.Trim()).SolveAsync;
            }
            else backup = (_, _) => throw new InvalidOperationException("No backup recognition key.");
            solve = solveOverride ?? ComposeSolvers(vendorSolve, backup, RecordProvider);
        }
        else solve = solveOverride ?? ((_, _) => throw new InvalidOperationException("No solver key."));
        manager.CaptchaRequestReceived += OnChallenge;
        manager.CaptchaOutcomeReceived += OnOutcome;
    }

    private void RecordProvider(string provider)
    {
        lastProvider = provider;
    }

    // Primary service first; any failure (not signed in, quota, outage) falls back to the backup
    // key so solving never stalls. Cancellation propagates untouched.
    internal static Func<string, CancellationToken, Task<string>> ComposeSolvers(
        Func<string, CancellationToken, Task<string>>? primary,
        Func<string, CancellationToken, Task<string>> failover,
        Action<string>? providerReport = null)
    {
        return async (image, stop) =>
        {
            if (primary is { } first)
            {
                try
                {
                    var answer = await first(image, stop);
                    providerReport?.Invoke("AION recognition");
                    return answer;
                }
                catch (Exception e) when (e is not OperationCanceledException)
                {
                    Diagnostics.TryLog("captcha-solver", "shared recognition unavailable (" + e.Message + "); using the backup service.");
                }
            }
            providerReport?.Invoke("backup");
            return await failover(image, stop);
        };
    }

    public bool Enabled => enabled;
    public int Solved => solved;
    public int Rejected => rejected;
    public int Failed => failed;
    public int Waiting => pending.Count;
    public string LastEvent => lastEvent;
    public DateTimeOffset? LastEventAt => lastEventAt;
    public IReadOnlyList<(DateTimeOffset At, string Text)> History
    {
        get { lock (historyLock) return [.. history]; }
    }

    // Every challenge image is archived beside the logs (with its outcome) so an operator can
    // review what the solver received — especially the answers the game rejected.
    internal static Func<string> SampleDirectoryResolver { get; set; } = () => Path.Combine(
        Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "Hexor", "ControlCenter", "CaptchaSamples");
    internal static Func<long>? TimeOverride;
    private const int MaximumSampleFiles = 200;

    private void SaveChallengeSample(int pid, string requestId, string imageBase64, string? mimeType)
    {
        try
        {
            var directory = SampleDirectoryResolver();
            Directory.CreateDirectory(directory);
            var extension = (mimeType ?? "").ToLowerInvariant() switch
            {
                "image/jpeg" or "image/jpg" => "jpg",
                "image/gif" => "gif",
                "image/bmp" => "bmp",
                _ => "png",
            };
            var stamp = TimeOverride is { } clock ? DateTimeOffset.FromUnixTimeMilliseconds(clock()) : DateTimeOffset.UtcNow;
            var safeRequest = string.Concat(requestId.Where(char.IsLetterOrDigit));
            if (safeRequest.Length == 0) safeRequest = "challenge";
            var path = Path.Combine(directory, $"{stamp:yyyyMMdd-HHmmssfff}-{pid}-{safeRequest}.{extension}");
            File.WriteAllBytes(path, Convert.FromBase64String(imageBase64.Trim()));
            PruneSamples(directory);
        }
        catch (Exception e) when (e is IOException or UnauthorizedAccessException or FormatException)
        {
            Diagnostics.TryLog("captcha-solver", $"pid {pid}: challenge sample could not be saved ({e.GetType().Name})");
        }
    }

    private void SaveOutcomeSample(int pid, string requestId, bool success, string message)
    {
        try
        {
            var directory = SampleDirectoryResolver();
            if (!Directory.Exists(directory)) return;
            var stamp = TimeOverride is { } clock ? DateTimeOffset.FromUnixTimeMilliseconds(clock()) : DateTimeOffset.UtcNow;
            var safeRequest = string.Concat(requestId.Where(char.IsLetterOrDigit));
            if (safeRequest.Length == 0) safeRequest = "challenge";
            var sidecar = Path.Combine(directory, $"{stamp:yyyyMMdd-HHmmssfff}-{pid}-{safeRequest}.outcome.txt");
            File.WriteAllText(sidecar, $"{stamp:O} pid={pid} challenge={requestId} outcome={(success ? "accepted" : "rejected")}" + (message.Length > 0 ? " message=" + message : "") + Environment.NewLine);
            PruneSamples(directory);
        }
        catch (Exception e) when (e is IOException or UnauthorizedAccessException)
        {
            Diagnostics.TryLog("captcha-solver", $"pid {pid}: challenge outcome could not be recorded ({e.GetType().Name})");
        }
    }

    private static void PruneSamples(string directory)
    {
        try
        {
            var files = new DirectoryInfo(directory).GetFiles().OrderBy(f => f.CreationTimeUtc).ToArray();
            for (var index = 0; index < files.Length - MaximumSampleFiles; index++) files[index].Delete();
        }
        catch (Exception e) when (e is IOException or UnauthorizedAccessException) { }
    }

    public string Describe() =>
        !enabled ? Hexor.Translations.Localize("Auto-resolve is not configured: no recognition service is available.")
        : Hexor.Translations.LocalizeFormat("Auto-resolve is active. Solved {0} · rejected {1} · failed {2}", solved, rejected, failed)
          + (pending.Count > 0 ? Hexor.Translations.LocalizeFormat(" · {0} in progress", pending.Count) : "")
          + (lastProvider.Length > 0 ? Hexor.Translations.LocalizeFormat(" · last answer via {0}", lastProvider) : "")
          + "\n" + Hexor.Translations.Localize(lastEvent);

    internal async void OnChallenge(int pid, string requestId, string imageBase64, string? mimeType)
    {
        if (!enabled) return;
        if (string.IsNullOrWhiteSpace(requestId) || string.IsNullOrWhiteSpace(imageBase64)) return;
        if (!seenRequests.TryAdd(requestId, 0))
        {
            SetEvent($"Challenge {requestId} was already handled.");
            return;
        }
        pending.TryAdd(requestId, 0);
        SetEvent($"Challenge {requestId} received; solving…");
        SaveChallengeSample(pid, requestId, imageBase64, mimeType);
        string answer = "";
        string error = "";
        try
        {
            using var deadline = new CancellationTokenSource(TimeSpan.FromSeconds(90));
            answer = await solve(imageBase64, deadline.Token);
        }
        catch (Exception e) when (e is not OperationCanceledException)
        {
            failed++;
            error = e.Message;
            SetEvent($"Challenge {requestId} could not be solved: {error}");
        }
        catch (OperationCanceledException)
        {
            failed++;
            error = "Solving timed out.";
            SetEvent($"Challenge {requestId} could not be solved: {error}");
        }
        pending.TryRemove(requestId, out _);
        try
        {
            // A human needs a moment to read the challenge; a random pause before answering
            // keeps the response time from looking machine-generated.
            var delay = minimumAnswerDelayMs == maximumAnswerDelayMs ? minimumAnswerDelayMs
                : Random.Shared.Next(minimumAnswerDelayMs, maximumAnswerDelayMs + 1);
            if (delay > 0) await Task.Delay(delay);
            var command = new { requestId, answer, error, forceLogout = false };
            if (SubmitOverride is { } submit) await submit(pid, "SubmitCaptchaAnswer", command);
            else await manager.SendCommandAsync(pid, "SubmitCaptchaAnswer", command);
            Diagnostics.TryLog("captcha-solver", $"pid {pid}: challenge {requestId} answered{(error.Length == 0 ? "" : " with issue " + error)}");
            if (error.Length == 0)
                SetEvent($"Challenge {requestId}: answer submitted; waiting for the game's result.");
        }
        catch (Exception e)
        {
            failed++;
            SetEvent($"Challenge {requestId} answer could not be delivered: {e.Message}");
        }
        Changed?.Invoke();
    }

    internal void OnOutcome(int pid, string requestId, bool success, string message)
    {
        if (string.IsNullOrWhiteSpace(requestId)) return;
        SaveOutcomeSample(pid, requestId, success, message);
        if (success)
        {
            solved++;
            SetEvent($"Challenge {requestId} was accepted by the game.");
        }
        else
        {
            rejected++;
            SetEvent($"Challenge {requestId} was rejected by the game" + (message.Length > 0 ? ": " + message : "."));
        }
        Diagnostics.TryLog("captcha-solver", $"pid {pid}: challenge {requestId} outcome={(success ? "accepted" : "rejected")}");
        Changed?.Invoke();
    }

    private void SetEvent(string text)
    {
        lastEvent = text;
        lastEventAt = DateTimeOffset.UtcNow;
        lock (historyLock)
        {
            history.Add((lastEventAt.Value, text));
            if (history.Count > 50) history.RemoveRange(0, history.Count - 50);
        }
    }

    public event Action? Changed;

    // Test seam: lets fixture tests capture the submitted answer without a live game pipe.
    internal Func<int, string, object?, Task>? SubmitOverride;

    public void Dispose()
    {
        manager.CaptchaRequestReceived -= OnChallenge;
        manager.CaptchaOutcomeReceived -= OnOutcome;
        vendorClient?.Dispose();
    }
}
